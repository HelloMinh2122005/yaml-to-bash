_SAFE_TOKEN_RE = re.compile(r"^[A-Za-z0-9._/@:+\-]+$")
_SAFE_NAME_RE = re.compile(r"^[A-Za-z0-9._/@:+\- ]+$")
_CONTROL_CHAR_RE = re.compile(r"[\r\n\t\x00-\x1f\x7f-\x9f]")


def sanitize_one_line(text: str) -> str:
    """Flatten string to one line and remove control characters."""
    return _CONTROL_CHAR_RE.sub(" ", text).strip()


def validate_safe_token(val: str, name: str, allow_spaces: bool = False) -> None:
    if not val:
        raise ValueError(f"{name} must not be empty")
    regex = _SAFE_NAME_RE if allow_spaces else _SAFE_TOKEN_RE
    if not regex.match(val) or "\n" in val or "\r" in val:
        raise ValueError(f"Unsafe characters in {name}: '{val}'")


def format_header_comment(job: Job, profile: Profile, job_rel: str) -> str:
    lines: List[str] = [
        "# ==============================================================================",
        f"# Azure DevOps Pipeline: {sanitize_one_line(job_rel)} ({profile.tool})",
        "# Prechecks:",
    ]
    prechecks = job.pre_run if job.pre_run else (job.invoke.precheck if job.invoke else [])
    for p in prechecks:
        phases = ", ".join(p.phases)
        actions = ", ".join(sorted(set(s.get("action", "") for s in p.result.values())))
        p_name = sanitize_one_line(p.name)
        lines.append(f"#   - {p_name} ({phases}): {actions}")

    lines.append("# Steps:")
    steps = job.invoke.runcommand.steps if job.invoke and job.invoke.runcommand else []
    for s in steps:
        s_name = sanitize_one_line(s.name)
        lines.append(f"#   - {s_name}")

    lines.append("# Columns:")
    for c in job.collect:
        c_name = sanitize_one_line(c.column)
        lines.append(f"#   - {c_name}")

    lines.append("# Post hooks:")
    for h in job.post_run:
        h_name = sanitize_one_line(h.name)
        lines.append(f"#   - {h_name}")

    actions = job.result_actions
    mutations = ["runCommand POST"]
    if actions & {"start", "start-stop"}:
        mutations.append("vm start")
    if actions & {"stop", "start-stop"}:
        mutations.append("deallocate")
    if actions & {"start-stop"}:
        mutations.append("powerOff")
    lines.append(f"# Reachable Azure mutations: {', '.join(mutations)}")
    lines.append("#")
    lines.append(f"# Generated by `{profile.tool} export-ado` — do not edit, regenerate.")
    lines.append(
        "# Known ADO limitation: re-running only a failed Invoke job re-publishes the fixed artifact name"
    )
    lines.append(
        "# 'y2-state-invoke'; to re-run after a failure, re-run the whole pipeline."
    )
    lines.append("# ==============================================================================")
    return "\n".join(lines)


def generate_pipeline_files(
    job: Job,
    profile: Profile,
    out_dir: Path,
    service_connection: str,
    environment: str,
    vm_image: Optional[str] = None,
    pool_name: Optional[str] = None,
    recollect_minutes: int = 0,
) -> Dict[str, str]:
    """Generate in-memory dictionary of {relative_path: file_content}."""
    repo_root = find_repo_root(job.yaml_path)
    if repo_root is None:
        raise ValueError("Job YAML must be inside a git repository")

    # Path validations
    for p_obj, p_name in [
        (out_dir, "output directory"),
        (job.yaml_path.resolve(), "job YAML path"),
        (job.output_csv.resolve(), "output CSV path"),
        (job.output_log.resolve(), "output Log path"),
    ]:
        try:
            p_obj.relative_to(repo_root)
        except ValueError:
            raise ValueError(f"{p_name} '{p_obj}' resolves outside the repository '{repo_root}'")

    job_rel = rel_posix(job.yaml_path, repo_root)
    dir_rel = rel_posix(out_dir, repo_root)
    parts_dir = get_parts_dir(job.output_csv)
    parts_rel = rel_posix(parts_dir, repo_root)
    out_csv_rel = rel_posix(job.output_csv, repo_root)
    out_log_rel = rel_posix(job.output_log, repo_root)
    payload_name = profile.remote_script_name
    payload_rel = f"{dir_rel}/payload/{payload_name}"
    plan_txt_rel = f"{dir_rel}/plan/explain.txt"
    plan_md_rel = f"{dir_rel}/plan/explain.md"

    # Token validations
    validate_safe_token(service_connection, "service connection", allow_spaces=True)
    validate_safe_token(environment, "environment", allow_spaces=True)
    if pool_name is not None:
        validate_safe_token(pool_name, "pool name", allow_spaces=True)
    if vm_image is not None:
        validate_safe_token(vm_image, "vm image")
        if vm_image.lower().startswith("windows"):
            raise ValueError(f"Windows VM image '{vm_image}' not supported; host runner needs bash for prechecks")

    for path_str in (job_rel, dir_rel, parts_rel, out_csv_rel, out_log_rel, payload_rel, plan_txt_rel, plan_md_rel):
        validate_safe_token(path_str, f"path {path_str}")

    # Pool YAML
    if pool_name is not None:
        pool_yaml = f"          name: {pool_name}"
    else:
        effective_image = vm_image or "ubuntu-latest"
        pool_yaml = f"          vmImage: {effective_image}"

    # Timing calculations
    sleep_sec = float(job.sleep_before_collect)
    delay_minutes = max(1, math.ceil(sleep_sec / 60.0))
    wait_timeout = delay_minutes + 15
    retries = int(job.collect_retries)
    interval = float(job.collect_retry_interval)
    collect_timeout = 120 + math.ceil((retries * interval) / 60.0)

    # 1. Compile payload
    compiled_payload, compile_errors = profile.compile_remote(job, run_id="preview", check_syntax=False)
    if compile_errors:
        raise RuntimeError(f"Payload compilation failed: {compile_errors}")

    # 2. Plan explain outputs
    rows, _, _ = read_input_csv(job.input, job=job, os_family=profile.os_family)
    plan_obj = build_plan(job, rows, profile)
    plan_txt = render_text(plan_obj)
    plan_md = render_md(plan_obj)

    # Load templates
    tpl_dir = Path(__file__).parent / "ado_templates"
    setup_tpl = (tpl_dir / "y2-setup.yml.tpl").read_text(encoding="utf-8")
    entry_tpl = (tpl_dir / "azure-pipelines.yml.tpl").read_text(encoding="utf-8")
    fleet_tpl = (tpl_dir / "y2-fleet-run.yml.tpl").read_text(encoding="utf-8")

    header_comment = format_header_comment(job, profile, job_rel)

    # Render y2-setup.yml
    y2_setup_content = setup_tpl.replace("__TOOL__", profile.tool)

    # Render azure-pipelines.yml
    entry_content = entry_tpl.replace("__HEADER_COMMENT__", header_comment)

    # Render recollect stages if needed
    recollect_block = ""
    if recollect_minutes > 0:
        recollect_wait_timeout = recollect_minutes + 15
        recollect_block = f"""
      # ---------- Optional: one more reader for ERROR:still_running VMs only ----------
      - job: Wait2
        dependsOn: Collect
        condition: and(succeeded(), eq(dependencies.Collect.outputs['collect.stillRunning'], 'true'))
        pool: server
        timeoutInMinutes: {recollect_wait_timeout}
        steps:
          - task: Delay@1
            inputs:
              delayForMinutes: '{recollect_minutes}'

      - job: Collect2
        dependsOn: Wait2
        pool:
{pool_yaml}
        timeoutInMinutes: {collect_timeout}
        steps:
          - checkout: self
          - template: y2-setup.yml
          - download: current
            artifact: y2-state-collect
          - bash: |
              set -euo pipefail
              if [ -f "$(Pipeline.Workspace)/y2-state-collect/y2-state-collect.tgz" ]; then
                tar -xzf "$(Pipeline.Workspace)/y2-state-collect/y2-state-collect.tgz" -C "$(Build.SourcesDirectory)"
              fi
            displayName: Restore run state
          - task: AzureCLI@2
            name: collect2
            displayName: "Re-collect still-running VMs"
            inputs:
              azureSubscription: {service_connection}
              scriptType: bash
              scriptLocation: inlineScript
              inlineScript: |
                set -uo pipefail
                set -f
                args=()
                for v in ${{ join(' ', parameters.vmFilter) }}; do
                  args+=(--vm "$v")
                done
                if [ "${{ parameters.parallel }}" -gt 0 ]; then
                  args+=(--parallel "${{ parameters.parallel }}")
                fi
                {profile.tool} run "{job_rel}" --phase collect -y "${{args[@]}}"
                rc=$?
                if [ "$rc" -eq 2 ]; then
                  echo "##vso[task.complete result=SucceededWithIssues;]"
                  rc=0
                fi
                exit "$rc"
          - bash: |
              set -euo pipefail
              OUT="$(Build.ArtifactStagingDirectory)/results-final"
              mkdir -p "$OUT"
              if [ -f "{out_csv_rel}" ]; then
                cp "{out_csv_rel}" "$OUT/"
              fi
              if [ -f "{out_log_rel}" ]; then
                cp "{out_log_rel}" "$OUT/"
              fi
            displayName: Stage final results
            condition: always()
          - publish: $(Build.ArtifactStagingDirectory)/results-final
            artifact: y2-results-final
            displayName: Publish final results
            condition: always()"""

    # Render y2-fleet-run.yml
    fleet_replacements = {
        "__HEADER_COMMENT__": header_comment,
        "__POOL_YAML__": pool_yaml,
        "__TOOL__": profile.tool,
        "__JOB_REL__": job_rel,
        "__PARTS_REL__": parts_rel,
        "__OUT_CSV_REL__": out_csv_rel,
        "__OUT_LOG_REL__": out_log_rel,
        "__PAYLOAD_REL__": payload_rel,
        "__PLAN_TXT_REL__": plan_txt_rel,
        "__PLAN_MD_REL__": plan_md_rel,
        "__ENVIRONMENT__": environment,
        "__SERVICE_CONNECTION__": service_connection,
        "__DELAY_MINUTES__": str(delay_minutes),
        "__WAIT_TIMEOUT__": str(wait_timeout),
        "__COLLECT_TIMEOUT__": str(collect_timeout),
        "__RECOLLECT_STAGES__": recollect_block,
    }

    fleet_content = fleet_tpl
    for k, v in fleet_replacements.items():
        fleet_content = fleet_content.replace(k, v)

    # Assert no leftovers
    assert "__" not in fleet_content, f"Leftover placeholders in fleet template"

    files: Dict[str, str] = {
        "azure-pipelines.yml": entry_content.rstrip() + "\n",
        "templates/y2-fleet-run.yml": fleet_content.rstrip() + "\n",
        "templates/y2-setup.yml": y2_setup_content.rstrip() + "\n",
        f"payload/{payload_name}": compiled_payload if compiled_payload.endswith("\n") else compiled_payload + "\n",
        "plan/explain.txt": plan_txt,
        "plan/explain.md": plan_md,
    }
    return files


def cmd_export_ado(args: argparse.Namespace, profile: Profile) -> int:
    """Execute export-ado subcommand (AC-16, AC-17, AC-18)."""
    yaml_path = Path(args.job_yaml).resolve()

    # 1. Validate job YAML
    job, result = validate_job_file(yaml_path, profile=profile)
    for w in result.warnings:
        print(f"WARNING: {w}", file=sys.stderr)
    for e in result.errors:
        print(f"ERROR: {e}", file=sys.stderr)
    if not result.is_valid or job is None:
        return 1

    # 2. Validate input CSV
    rows, _, csv_result = read_input_csv(job.input, job=job, os_family=profile.os_family)
    for w in csv_result.warnings:
        print(f"WARNING: {w}", file=sys.stderr)
    for e in csv_result.errors:
        print(f"ERROR: {e}", file=sys.stderr)
    if not csv_result.is_valid:
        return 1

    # 3. Check mutually exclusive pool / vm-image
    vm_image = getattr(args, "vm_image", None)
    pool = getattr(args, "pool", None)
    if vm_image is not None and pool is not None:
        print("ERROR: --vm-image and --pool are mutually exclusive", file=sys.stderr)
        return 1

    out_dir = Path(args.output).resolve()
    service_connection = getattr(args, "service_connection", "")
    environment = getattr(args, "environment", "")
    recollect_minutes = getattr(args, "recollect_minutes", 0) or 0
    check_mode = getattr(args, "check", False)

    try:
        files = generate_pipeline_files(
            job=job,
            profile=profile,
            out_dir=out_dir,
            service_connection=service_connection,
            environment=environment,
            vm_image=vm_image,
            pool_name=pool,
            recollect_minutes=recollect_minutes,
        )
    except Exception as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 1

    if check_mode:
        missing = []
        differs = []
        for relpath, content in files.items():
            target_path = out_dir / relpath
            if not target_path.is_file():
                missing.append(relpath)
            else:
                existing_bytes = target_path.read_bytes()
                expected_bytes = content.encode("utf-8")
                if existing_bytes != expected_bytes:
                    differs.append(relpath)

        if missing or differs:
            for m in missing:
                print(f"MISSING: {m}", file=sys.stderr)
            for d in differs:
                print(f"DIFFERS: {d}", file=sys.stderr)
            return 1
        return 0

    # Write files LF / UTF-8
    for relpath, content in files.items():
        target_path = out_dir / relpath
        target_path.parent.mkdir(parents=True, exist_ok=True)
        with open(target_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)

    print(f"Exported ADO pipeline for {profile.tool} to: {out_dir}")
    return 0
